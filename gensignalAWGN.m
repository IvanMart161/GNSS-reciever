% =========================================================================
% ШАГ 1: Генерация GPS сигнала на ПЧ 9.548 МГц с шумом
% =========================================================================
clear; clc; close all;

fs = 38.192e6;         % Частота дискретизации АЦП (38.192 МГц)
f_if = 9.548e6;        % Промежуточная частота (9.548 МГц)
f_doppler = 521;       % Частота Доплера несущей (Гц)
f_chip = 1.023e6;      % Номинальная скорость C/A кода (Гц)
f_L1 = 1575.42e6;      % Частота несущей GPS L1 (Гц)
T_sim = 3;           % Длительность (0.5 c)
t = 0 : 1/fs : T_sim - 1/fs;
N = length(t);

% 1. Генерация C/A кода (PRN 1)
G1 = ones(1, 10); G2 = ones(1, 10);
PRN_code = zeros(1, 1023);
for i = 1:1023
    PRN_code(i) = mod(G1(10) + mod(G2(2) + G2(6), 2), 2);
    G1 = [mod(G1(3) + G1(10), 2), G1(1:9)];
    G2 = [mod(G2(2) + G2(3) + G2(6) + G2(8) + G2(9) + G2(10), 2), G2(1:9)];
end
PRN_bpsk = 1 - 2 * PRN_code; % BPSK: 0->1, 1->-1

% 2. ДОБАВЛЯЕМ СЛУЧАЙНУЮ ЗАДЕРЖКУ И КОДОВЫЙ ДОПЛЕР
delay_seconds = 342.45 / f_chip; % Можешь вернуть задержку, например: 342.45 / f_chip;


% Расчет реальной скорости кода из-за эффекта Доплера
f_code_doppler = f_doppler * (f_chip / f_L1); % ~ 0.338 Гц для Доплера 521 Гц
f_chip_dynamic = f_chip + f_code_doppler;

% Растягиваем код на частоту дискретизации АЦП с учетом задержки и Доплера кода
%chip_indices = mod(floor(max(t - delay_seconds, 0) * f_chip_dynamic), 1023) + 1;
chip_indices = mod(floor((t - delay_seconds) * f_chip_dynamic), 1023) + 1;
baseband_signal = PRN_bpsk(chip_indices);


%% ФОРМИРУЕМ ИНФОРМАЦИОННОЕ СООБЩЕНИЕ (50 БИТ/С)
% 1. Генерируем преамбулу: 30 чередующихся бит (1,0,1,0...) = 600 мс эфира
% Это идеальный сигнал для нашей гистограммы переходов!
preamble_bits = repmat([1, 0], 1, 15);

% Любой твой текст
user_text = 'Hello World';

% 2. Формируем полезное сообщение
msg = ['$', user_text]; 
bin_msg = reshape(dec2bin(msg, 8).' - '0', 1, []);

% 3. Склеиваем преамбулу и сообщение
full_bin_msg = [preamble_bits, bin_msg];

% 4. По стандарту GPS: 0 -> +1, 1 -> -1 (BPSK)
nav_data_bpsk = 1 - 2 * full_bin_msg; 

% Рассчитываем, сколыько отсчетов АЦП занимает 1 бит (20 мс)
samples_per_bit = round(20e-3 * fs);

% Растягиваем каждый бит на 20 мс
expanded_data = repelem(nav_data_bpsk, samples_per_bit);

% Выравниваем массив данных под длину вектора времени t (N отсчетов)
if length(expanded_data) >= N
    data_mod = expanded_data(1:N);
else
    % Если сообщение закончилось, добиваем эфир единицами (фаза не меняется)
    data_mod = [expanded_data, ones(1, N - length(expanded_data))];
end

%% Перенос на ПЧ

% 3. Перенос на ПЧ (Умножение на несущую 9.548 МГц)
carrier = cos(2 * pi * (f_if + f_doppler) * t);

clean_if_signal = baseband_signal .* data_mod .* carrier;

%% Задаем ОСШ
% 4. Задаем SNR = 10 дБ
SNR_db = -20; 

% Рассчитываем мощность чистого сигнала
signal_power = mean(clean_if_signal.^2);

% Переводим SNR из дБ в разы
SNR_linear = 10^(SNR_db / 10);

% Находим требуемую мощность шума
noise_power = signal_power / SNR_linear;

% Генерируем нормальный (гауссовский) шум
noise = sqrt(noise_power) * randn(size(clean_if_signal));

% Итоговый зашумленный сигнал
if_signal = clean_if_signal + noise;

% =========================================================================
% Моделирование ПАВ-фильтра (SAW Filter)
% =========================================================================
f_pass_low  = f_if - 2.0e6; % 7.548 МГц
f_pass_high = f_if + 2.0e6; % 11.548 МГц

% Проектируем полосовой фильтр Баттерворта 4-го порядка
[b_saw, a_saw] = butter(4, [f_pass_low, f_pass_high] / (fs/2), 'bandpass');

% Пропускаем наш зашумленный сигнал через ПАВ-фильтр
if_signal = filter(b_saw, a_saw, if_signal);

% % =========================================================================
% % Жесткое квантование сигнала через 1-битный АЦП (0 и 1)
% % =========================================================================
% adc_1bit = if_signal > 0;
% 
% % Сохраняем в файл именно БИТЫ (0 и 1)
% disp('Сохранение 1-битного сигнала АЦП в gps_if_signal.txt...');
% writematrix(double(adc_1bit(:)), 'gps_if_signal.txt');

% =========================================================================
% Жесткое квантование сигнала через 1-битный АЦП (0 и 1)
% =========================================================================
% Переводим логический массив в беззнаковые 8-битные целые (1 байт на отсчет)
adc_1bit = uint8(if_signal > 0);

% Сохраняем в бинарный файл .bin
disp('Сохранение 1-битного сигнала АЦП в gps_if_signal.bin...');
fid = fopen('gps_if_signal.bin', 'wb');
if fid == -1
    error('Не удалось создать файл gps_if_signal.bin');
end
fwrite(fid, adc_1bit, 'uint8');
fclose(fid);
disp('Готово!');

% =========================================================================
% 5. Построение графиков
% =========================================================================
figure('Name', 'Сгенерированный зашумленный сигнал на ПЧ');
subplot(2,1,1);
plot(t(1:200)*1e6, if_signal(1:200), 'b');
title(['Временная область с шумом и задержкой (SNR = ' num2str(SNR_db) ' дБ)']); 
xlabel('Время (мкс)'); ylabel('Амплитуда'); grid on;

subplot(2,1,2);
Y = fft(if_signal);
f = (0:N/2) * (fs / N);
plot(f/1e6, 20*log10(abs(Y(1:N/2+1))), 'r');
title('Спектр зашумленного сигнала'); 
xlabel('Частота (МГц)'); ylabel('дБ');
xlim([0 fs/2/1e6]); grid on;

